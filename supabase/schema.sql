create table if not exists public.categories (
  id bigint generated by default as identity primary key,
  name text not null,
  almacen text not null default 'las-flores',
  created_at timestamptz not null default now(),
  unique (almacen, name)
);

create table if not exists public.movements (
  id text primary key,
  codigo text not null,
  descripcion text not null,
  cantidad numeric not null check (cantidad > 0),
  unidad_medida text,
  costo numeric not null default 0,
  stock_minimo numeric not null default 0,
  valor numeric not null default 0,
  fecha date not null,
  responsable text not null,
  area text not null,
  categoria text,
  tipo text not null check (tipo in ('Entrada', 'Salida')),
  imagen text,
  motivo text,
  almacen text not null default 'las-flores',
  created_at timestamptz not null default now()
);

create index if not exists movements_codigo_idx on public.movements (upper(trim(codigo)));
create index if not exists movements_fecha_idx on public.movements (fecha);
create index if not exists movements_almacen_idx on public.movements (almacen);

-- Copia congelada de cada registro (número correlativo + lista de productos
-- tal como se registró / imprimió). No cambia aunque se edite o borre un movimiento.
create table if not exists public.comprobantes (
  id            text primary key,
  tipo          text not null check (tipo in ('Entrada', 'Salida')),
  numero        integer not null,
  periodo       text not null,             -- año; el correlativo reinicia cada año
  fecha         date not null,
  area          text not null,
  responsable   text not null,
  observaciones text,
  items         jsonb not null default '[]'::jsonb,
  movement_ids  text[] not null default '{}',
  almacen       text not null default 'las-flores',
  created_at    timestamptz not null default now(),
  unique (almacen, tipo, periodo, numero)
);

create index if not exists comprobantes_created_at_idx on public.comprobantes (created_at);
create index if not exists comprobantes_almacen_idx on public.comprobantes (almacen);

-- Traspaso de mercadería entre almacenes: el origen la crea (descuenta su
-- stock al toque) y queda "pendiente" hasta que el destino la recibe (recién
-- ahí suma su propio stock) o la rechaza. Es la única tabla donde una sesión
-- ve/toca legítimamente filas que no son 100% "suyas" — ver el trigger más
-- abajo, que además de RLS decide qué le permite cambiar a cada lado.
create table if not exists public.traspasos (
  id                    text primary key,
  numero                integer not null,
  periodo               text not null,
  almacen_origen        text not null,
  almacen_destino       text not null check (almacen_destino <> almacen_origen),
  estado                text not null default 'pendiente' check (estado in ('pendiente', 'recibido', 'cancelado')),
  fecha_envio           date not null,
  responsable_envio     text not null,
  motivo                text,
  items                 jsonb not null default '[]'::jsonb,
  movement_ids_salida   text[] not null default '{}',
  fecha_recepcion       date,
  responsable_recepcion text,
  items_recibidos       jsonb,
  movement_ids_entrada  text[] not null default '{}',
  motivo_cancelacion    text,
  created_at            timestamptz not null default now(),
  unique (almacen_origen, periodo, numero)
);

create index if not exists traspasos_origen_idx on public.traspasos (almacen_origen);
create index if not exists traspasos_destino_idx on public.traspasos (almacen_destino);

alter table public.categories enable row level security;
