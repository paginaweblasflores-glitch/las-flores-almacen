-- El almacén de la sesión viaja en el JWT (app_metadata), no en un mapeo
-- de correos hardcodeado dentro de cada política. Ver el paso 4 de
-- supabase/migration-fase6.sql para asignárselo a cada usuario.
create or replace function public.almacen_actual()
returns text
language sql
stable
as $$
  select nullif(
    (current_setting('request.jwt.claims', true)::jsonb -> 'app_metadata' ->> 'almacen'),
    ''
  );
$$;

-- La cuenta Administrador (rol en el JWT, no un almacén más) ve y escribe
-- CUALQUIER almacén — ver supabase/migration-fase9.sql para el detalle y
-- las advertencias de precedencia SQL al sumar este OR a cada política.
create or replace function public.es_admin()
returns boolean
language sql
stable
as $$
  select coalesce(
    (current_setting('request.jwt.claims', true)::jsonb -> 'app_metadata' ->> 'role') = 'admin',
    false
  );
$$;

-- Cada cuenta de acceso (CUENTAS en src/supabaseClient.ts) solo ve y escribe
-- las filas de SU "almacen" (o cualquiera, si es Administrador). Agregar una
-- cuenta nueva no toca estas políticas: solo hace falta el UPDATE del
-- paso 4 en migration-fase6.sql.
drop policy if exists "categories_public_access" on public.categories;
drop policy if exists "categories_por_almacen" on public.categories;
create policy "categories_por_almacen"
  on public.categories for all
  to authenticated
  using (almacen = public.almacen_actual() or public.es_admin())
  with check (almacen = public.almacen_actual() or public.es_admin());

drop policy if exists "movements_public_access" on public.movements;
drop policy if exists "movements_por_almacen" on public.movements;
create policy "movements_por_almacen"
  on public.movements for all
  to authenticated
  using (almacen = public.almacen_actual() or public.es_admin())
  with check (almacen = public.almacen_actual() or public.es_admin());

drop policy if exists "comprobantes_public_access" on public.comprobantes;
drop policy if exists "comprobantes_por_almacen" on public.comprobantes;
create policy "comprobantes_por_almacen"
  on public.comprobantes for all
  to authenticated
  using (almacen = public.almacen_actual() or public.es_admin())
